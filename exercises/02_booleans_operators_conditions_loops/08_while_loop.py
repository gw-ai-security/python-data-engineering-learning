# 08 While Loop

page = 1
max_page = 4

print("=============================================")

while page <= max_page:
    print(f"Processing page {page}")
    page += 1

print("=============================================")

attempt = 1
max_attempts = 3

while attempt <= max_attempts:
    print(f"Attempt {attempt}")
    attempt += 1

print("Maximum attempts reached")
print("=============================================")
